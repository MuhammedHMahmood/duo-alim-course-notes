"""Sync study notes to docs/ and update mkdocs.yml navigation."""

import html
import json
import re
import shutil
import yaml
from datetime import datetime
from pathlib import Path

from common import load_config, SUBJECTS_DIR, DOCS_DIR, PROJECT_ROOT

WEEKLY_SRC_DIR = PROJECT_ROOT / "weekly" / "reviews"
WEEKLY_DOCS_DIR = DOCS_DIR / "weekly"
QUIZ_SRC_DIR = PROJECT_ROOT / "weekly" / "quizzes"
QUIZ_DOCS_DIR = WEEKLY_DOCS_DIR / "quiz"


def sync_notes_to_docs():
    """Copy all notes from subjects/*/notes/ to docs/{subject}/{course}/."""
    for subject_dir in sorted(SUBJECTS_DIR.iterdir()):
        if not subject_dir.is_dir():
            continue
        subject = subject_dir.name

        for course_dir in sorted(subject_dir.iterdir()):
            if not course_dir.is_dir():
                continue
            course = course_dir.name
            notes_dir = course_dir / "notes"

            if not notes_dir.exists():
                continue

            notes = list(notes_dir.glob("*.md"))
            if not notes:
                continue

            docs_dest = DOCS_DIR / subject / course
            docs_dest.mkdir(parents=True, exist_ok=True)

            for note_file in notes:
                shutil.copy2(note_file, docs_dest / note_file.name)


def sync_weekly_reviews():
    """Copy weekly review pages from weekly/reviews/ to docs/weekly/."""
    if not WEEKLY_SRC_DIR.exists():
        return

    reviews = list(WEEKLY_SRC_DIR.glob("*.md"))
    if not reviews:
        return

    WEEKLY_DOCS_DIR.mkdir(parents=True, exist_ok=True)
    for review_file in reviews:
        content = review_file.read_text(encoding="utf-8")
        # The quiz is generated by a separate, later run, so only link it once it exists.
        if (QUIZ_SRC_DIR / f"{review_file.stem}.json").exists():
            content = _add_quiz_link(content, review_file.stem)
        (WEEKLY_DOCS_DIR / review_file.name).write_text(content, encoding="utf-8")


def _add_quiz_link(content, week_end):
    """Insert a link to that week's quiz right under the page title."""
    link = f"> Ready to test yourself? [Take the weekly quiz →](quiz/{week_end}.md)"
    lines = content.split("\n")
    for i, line in enumerate(lines):
        if line.startswith("# "):
            return "\n".join(lines[: i + 1] + ["", link] + lines[i + 1 :])
    return link + "\n\n" + content


def generate_weekly_index():
    """Generate docs/weekly/index.md listing every week, most recent first."""
    if not WEEKLY_DOCS_DIR.exists():
        return

    rows = []
    for review_file in sorted(WEEKLY_DOCS_DIR.glob("*.md"), reverse=True):
        if review_file.name == "index.md":
            continue
        try:
            dt = datetime.strptime(review_file.stem, "%Y-%m-%d")
            display = dt.strftime("%b %d, %Y")
        except ValueError:
            display = review_file.stem
        rows.append(f"| [Week ending {display}]({review_file.name}) |")

    if not rows:
        return

    content = f"""# Weekly Review

A condensed recap of each week's lessons across all active classes. Read the recap,
then test yourself with the [weekly quiz](quiz/index.md).

| Week |
|------|
{chr(10).join(rows)}
"""
    (WEEKLY_DOCS_DIR / "index.md").write_text(content, encoding="utf-8")


def _week_label(week_end):
    try:
        return datetime.strptime(week_end, "%Y-%m-%d").strftime("%b %d, %Y")
    except ValueError:
        return week_end


def _quiz_page(quiz):
    """Render a quiz page: a heading plus a div that quiz.js turns into the quiz.

    The questions travel as an HTML attribute rather than a <script> block so the
    site search index doesn't pick up the raw JSON.
    """
    end = quiz["week_end"]
    start_dt = datetime.strptime(quiz["week_start"], "%Y-%m-%d")
    end_dt = datetime.strptime(end, "%Y-%m-%d")
    date_range = f"{start_dt.strftime('%b %d')} - {end_dt.strftime('%b %d, %Y')}"
    data = html.escape(json.dumps(quiz, ensure_ascii=False, separators=(",", ":")), quote=True)

    return f"""# Weekly Quiz — Week of {date_range}

Multiple-choice check on this week's lessons across all active classes. Pick an answer to
see right away whether it's correct and why. Want a refresher first?
[Read the weekly review](../{end}.md).

<div class="duo-quiz" data-quiz="{data}">Enable JavaScript to take this quiz.</div>
"""


def sync_weekly_quizzes():
    """Render weekly/quizzes/*.json into docs/weekly/quiz/*.md pages."""
    if not QUIZ_SRC_DIR.exists():
        return

    quizzes = list(QUIZ_SRC_DIR.glob("*.json"))
    if not quizzes:
        return

    QUIZ_DOCS_DIR.mkdir(parents=True, exist_ok=True)
    for quiz_file in quizzes:
        quiz = json.loads(quiz_file.read_text(encoding="utf-8"))
        (QUIZ_DOCS_DIR / f"{quiz_file.stem}.md").write_text(_quiz_page(quiz), encoding="utf-8")


def generate_quiz_index():
    """Generate docs/weekly/quiz/index.md listing every quiz, most recent first."""
    rows = []
    for quiz_file in sorted(QUIZ_SRC_DIR.glob("*.json"), reverse=True):
        quiz = json.loads(quiz_file.read_text(encoding="utf-8"))
        count = sum(len(s["questions"]) for s in quiz["sections"])
        rows.append(f"| [Week ending {_week_label(quiz_file.stem)}]({quiz_file.stem}.md) | {count} |")

    if not rows:
        return

    content = f"""# Weekly Quiz

Multiple-choice quizzes on each week's lessons across all active classes. For a refresher
before you start, see the [weekly review](../index.md).

| Week | Questions |
|------|-----------|
{chr(10).join(rows)}
"""
    (QUIZ_DOCS_DIR / "index.md").write_text(content, encoding="utf-8")


def _extract_topic(md_path):
    """Extract a short topic label from a note file for nav sidebar.

    Reads the first 20 lines and tries multiple extraction strategies:
    - Tafseer: Surah name (e.g., "Surah Al-Duha")
    - Hadith: Hadith number (e.g., "Hadith #20")
    - All: Bold terms, "focused on" / "covered" phrases, parenthetical
      Arabic terms, or first Key Theme from the Session Overview.
    """
    try:
        with open(md_path, "r", encoding="utf-8") as f:
            lines = [f.readline() for _ in range(40)]

        # --- Tafseer: Extract surah name ---
        for line in lines[:15]:
            line = line.strip()
            m = re.match(r'\*\*Surah Covered:\*\*\s*(.+)', line)
            if m:
                return _clean_surah_name(m.group(1))
            m = re.match(r'\*\*Surah:\*\*\s*(.+)', line)
            if m:
                return _clean_surah_name(m.group(1))
            m = re.match(r'##\s+Surah Covered:\s*(.+)', line)
            if m:
                return _clean_surah_name(m.group(1))
            m = re.match(r'##\s+(Surah\s+(?!Covered).+)', line)
            if m:
                return _clean_surah_name(m.group(1))

        # --- Extract Session Overview text ---
        overview_text = ""
        in_overview = False
        for line in lines:
            stripped = line.strip()
            if stripped.startswith("## Session Overview"):
                in_overview = True
                continue
            if in_overview:
                if stripped.startswith("---") or stripped.startswith("##"):
                    break
                overview_text += stripped + " "

        if overview_text:
            topic = _topic_from_overview(overview_text)
            if topic:
                return topic

        # --- Extract first Key Theme as last resort ---
        in_themes = False
        for line in lines:
            stripped = line.strip()
            if stripped.startswith("## Key Themes"):
                in_themes = True
                continue
            if in_themes:
                if stripped.startswith("---") or stripped.startswith("##"):
                    break
                # Look for "- **Topic**: description" or "- Topic"
                m = re.match(r'-\s+\*\*([^*]+)\*\*', stripped)
                if m:
                    return _truncate(m.group(1), 30)
                m = re.match(r'-\s+(.+?)(?::|$)', stripped)
                if m and len(m.group(1).strip()) > 3:
                    return _truncate(m.group(1).strip(), 40)

        # --- Surah in heading fallback ---
        for line in lines[:15]:
            line = line.strip()
            if line.startswith("# "):
                title = line.lstrip("# ").strip()
                m = re.search(r'(Surah\s+\S+(?:\s+\S+)?)', title)
                if m:
                    return _clean_surah_name(m.group(1))

    except Exception:
        pass
    return None


def _topic_from_overview(text):
    """Extract a short topic label from the Session Overview paragraph."""

    # --- Hadith number ---
    m = re.search(r'[Hh]adith\s*(?:#|No\.?\s*|number\s*)(\d+)', text)
    if m:
        return f"Hadith #{m.group(1)}"

    # --- Bold terms (most specific) ---
    bold = re.findall(r'\*\*([^*]+)\*\*', text)
    if bold:
        return _truncate(bold[0], 30)

    # --- "focused on" / "covering" / "covered" pattern ---
    # e.g. "focused on the nullifiers of wudu and the obligations of ghusl"
    # e.g. "covered fi'il mudareh (present/future tense verbs)"
    for pattern in [
        r'(?:focused|focusing)\s+on\s+(?:the\s+)?(?:concept\s+of\s+)?(.+?)(?:\.|,\s+(?:and|with|the instructor|the class|ranging|including|examining|emphasizing))',
        r'(?:covered|covering)\s+(?:the\s+)?(.+?)(?:\.|,\s+(?:and|with|the instructor|the class|ranging|including|focusing))',
        r'(?:introduced?|introducing)\s+(?:the\s+)?(.+?)(?:\.|,\s+(?:and|with|the))',
    ]:
        m = re.search(pattern, text, re.IGNORECASE)
        if m:
            topic = m.group(1).strip()
            # Extract parenthetical Arabic term if present
            arabic = _extract_parenthetical(topic)
            if arabic:
                return _truncate(arabic, 30)
            # Clean up the English topic
            topic = _clean_topic_phrase(topic)
            if topic and len(topic) > 2:
                return _truncate(topic, 30)

    # --- "Introduction to X" pattern ---
    m = re.search(r'[Ii]ntroduction\s+to\s+(.+?)(?:\.|,|\()', text)
    if m:
        topic = m.group(1).strip()
        arabic = _extract_parenthetical(topic + text[m.end():m.end()+50])
        if arabic:
            return _truncate(f"Intro to {arabic}", 30)
        return _truncate(f"Intro to {_clean_topic_phrase(topic)}", 30)

    # --- "about [topic]" pattern ---
    m = re.search(r'about\s+(?:the\s+)?(.+?)(?:\.|,|\()', text)
    if m:
        topic = _clean_topic_phrase(m.group(1).strip())
        if topic and len(topic) > 2:
            return _truncate(topic, 30)

    # --- Parenthetical Arabic terms anywhere in overview ---
    # e.g. "(wudu)", "(ghusl)", "(istinja)", "(bid'a)"
    parens = re.findall(r'\(([a-z][a-z\' -]{2,25})\)', text, re.IGNORECASE)
    # Filter out common non-topic parentheticals
    skip = {'e.g', 'i.e', 'fard', 'wajib', 'sunnah', 'nafl', 'pbuh',
            'may allah', 'rahmatullahi', 'peace be upon him'}
    for p in parens:
        if p.lower() not in skip and not p[0].isupper():
            return _truncate(p[0].upper() + p[1:], 30)

    return None


def _extract_parenthetical(text):
    """Extract a short Arabic term from parentheses, e.g. '(ghusl)' -> 'Ghusl'."""
    m = re.search(r'\(([a-z][a-z\' -]{2,30})\)', text, re.IGNORECASE)
    if m:
        term = m.group(1).strip()
        skip = {'e.g', 'i.e', 'fard', 'wajib', 'sunnah', 'nafl'}
        if term.lower() not in skip:
            return term[0].upper() + term[1:]
    return None


def _clean_topic_phrase(topic):
    """Clean a topic phrase to a short, readable label."""
    # Remove leading articles and filler words
    topic = re.sub(
        r'^(?:the\s+)?(?:concept\s+of\s+|importance\s+of\s+|'
        r'significance\s+of\s+|foundations?\s+of\s+|'
        r'fundamentals?\s+of\s+|basics?\s+of\s+)?(?:the\s+)?',
        '', topic, flags=re.IGNORECASE,
    ).strip()
    # Capitalize first letter
    if topic:
        topic = topic[0].upper() + topic[1:]
    return topic


def _truncate(text, max_len):
    """Truncate text to max_len, adding '...' if needed."""
    text = text.strip()
    if len(text) > max_len:
        return text[:max_len - 3] + "..."
    return text


def _clean_surah_name(raw):
    """Clean up a surah name to a short display label.

    'Surah Al-Duha (Chapter 93), with references...' -> 'Surah Al-Duha'
    'Surah Al-Asr (Completion of Tafseer)' -> 'Surah Al-Asr (contd.)'
    """
    # Remove markdown formatting
    raw = raw.replace("*", "").strip()

    # Extract just "Surah X" or "Surah Al-X"
    m = re.match(r'(Surah\s+(?:Al[- ]|At[- ]|Az[- ]|Ad[- ])?[\w\'-]+)', raw)
    if m:
        name = m.group(1)
    else:
        name = raw

    # Check if it's a continuation
    lower = raw.lower()
    if "contd" in lower or "continuation" in lower or "continued" in lower or "completion" in lower:
        name += " (contd.)"
    elif "part" in lower or "session" in lower or "segment" in lower:
        # Extract part number
        pm = re.search(r'(?:part|session|segment)\s*(\d+)', lower)
        if pm:
            name += f" (Part {pm.group(1)})"
    elif "ayat" in lower or "ayaat" in lower:
        # Extract ayah range
        am = re.search(r'(?:ayat|ayaat)\s*([\d\-]+)', lower)
        if am:
            name += f" (Ayat {am.group(1)})"

    # Truncate if too long
    if len(name) > 50:
        name = name[:47] + "..."

    return name


def generate_course_index(subject, course, docs_course_dir, class_meta):
    """Generate an index.md for a course with a table of sessions."""
    meta = class_meta.get((subject, course), {})
    semester = meta.get("semester", "")
    course_name = meta.get("name", f"{subject.upper()} {course}")

    title = f"{subject.upper()} {course}"
    if semester:
        title += f" ({semester})"

    rows = []
    for note_file in sorted(docs_course_dir.glob("*.md")):
        if note_file.name == "index.md":
            continue
        date_str = note_file.stem
        try:
            dt = datetime.strptime(date_str, "%Y-%m-%d")
            date_display = dt.strftime("%b %d, %Y")
        except ValueError:
            date_display = date_str

        topic = _extract_topic(note_file) or "—"
        rows.append(f"| [{date_display}]({note_file.name}) | {topic} |")

    if not rows:
        return

    content = f"""# {title}

{course_name}

| Date | Topic |
|------|-------|
{chr(10).join(rows)}
"""

    index_path = docs_course_dir / "index.md"
    index_path.write_text(content, encoding="utf-8")


SEASON_RANK = {"spring": 0, "summer": 1, "fall": 2, "winter": 3}


def _semester_sort_key(semester):
    """Sort key for a 'Season Year' string, e.g. 'Fall 2025' -> (2025, 2)."""
    parts = semester.split()
    if len(parts) == 2:
        season, year = parts
        if year.isdigit():
            return (int(year), SEASON_RANK.get(season.lower(), 99))
    return (0, 99)


def _build_course_nav(subject, course, course_dir, class_meta):
    """Generate the course index page and return its session nav entries."""
    generate_course_index(subject, course, course_dir, class_meta)

    course_nav = [{"Overview": f"{subject}/{course}/index.md"}]

    for note_file in sorted(course_dir.glob("*.md")):
        if note_file.name == "index.md":
            continue
        date_str = note_file.stem
        try:
            dt = datetime.strptime(date_str, "%Y-%m-%d")
            display = dt.strftime("%b %d")
        except ValueError:
            display = date_str

        topic = _extract_topic(note_file)
        label = f"{display} - {topic}" if topic else display

        rel_path = f"{subject}/{course}/{note_file.name}"
        course_nav.append({label: rel_path})

    return course_nav


def _build_weekly_nav():
    """Generate the weekly index page and return its nav entries, or None if empty."""
    generate_weekly_index()
    if not WEEKLY_DOCS_DIR.exists():
        return None

    review_files = sorted(
        (f for f in WEEKLY_DOCS_DIR.glob("*.md") if f.name != "index.md"),
        reverse=True,
    )
    if not review_files:
        return None

    entries = [{"Overview": "weekly/index.md"}]
    for review_file in review_files:
        try:
            dt = datetime.strptime(review_file.stem, "%Y-%m-%d")
            label = f"Week ending {dt.strftime('%b %d, %Y')}"
        except ValueError:
            label = review_file.stem
        entries.append({label: f"weekly/{review_file.name}"})

    return entries


def _build_quiz_nav():
    """Generate the quiz index page and return its nav entries, or None if empty."""
    if not QUIZ_SRC_DIR.exists():
        return None
    generate_quiz_index()

    quiz_files = sorted(
        (f for f in QUIZ_DOCS_DIR.glob("*.md") if f.name != "index.md"),
        reverse=True,
    )
    if not quiz_files:
        return None

    entries = [{"Overview": "weekly/quiz/index.md"}]
    for quiz_file in quiz_files:
        entries.append({f"Week ending {_week_label(quiz_file.stem)}": f"weekly/quiz/{quiz_file.name}"})

    return entries


def build_nav():
    """Build mkdocs.yml nav: Home, Weekly (Review + Quiz dropdowns), Active Classes, Archived Classes."""
    nav = [{"Home": "index.md"}]

    # Nested one level down so they render as collapsible dropdowns — with the theme's
    # navigation.sections feature, top-level sections are always shown expanded.
    weekly = []
    weekly_nav = _build_weekly_nav()
    if weekly_nav:
        weekly.append({"Weekly Review": weekly_nav})
    quiz_nav = _build_quiz_nav()
    if quiz_nav:
        weekly.append({"Weekly Quiz": quiz_nav})
    if weekly:
        nav.append({"Weekly": weekly})

    config = load_config()

    class_meta = {}
    for c in config["classes"]:
        key = (c["subject"], c["course"])
        class_meta[key] = c

    active_courses = []
    archived_by_semester = {}

    for subject_dir in sorted(DOCS_DIR.iterdir()):
        if not subject_dir.is_dir():
            continue
        subject = subject_dir.name
        if subject in ("stylesheets", "assets", "weekly"):
            continue

        for course_dir in sorted(subject_dir.iterdir()):
            if not course_dir.is_dir():
                continue
            course = course_dir.name
            meta = class_meta.get((subject, course), {})
            semester = meta.get("semester", "")

            course_nav = _build_course_nav(subject, course, course_dir, class_meta)
            if len(course_nav) <= 1:
                continue  # no session notes yet

            if meta.get("active", False):
                label = f"{subject.upper()} {course} ({semester})" if semester else f"{subject.upper()} {course}"
                active_courses.append((label, course_nav))
            else:
                label = f"{subject.upper()} {course}"
                archived_by_semester.setdefault(semester or "Unknown", []).append((label, course_nav))

    active_courses.sort(key=lambda x: x[0])
    if active_courses:
        nav.append({"Active Classes": [{label: n} for label, n in active_courses]})

    archived_nav = []
    for semester in sorted(archived_by_semester, key=_semester_sort_key, reverse=True):
        courses = sorted(archived_by_semester[semester], key=lambda x: x[0])
        archived_nav.append({semester: [{label: n} for label, n in courses]})

    if archived_nav:
        nav.append({"Archived Classes": archived_nav})

    return nav


def update_mkdocs_yml(nav):
    """Update the mkdocs.yml file with new navigation."""
    mkdocs_path = PROJECT_ROOT / "mkdocs.yml"

    with open(mkdocs_path, "r", encoding="utf-8") as f:
        mkdocs_config = yaml.safe_load(f)

    mkdocs_config["nav"] = nav
    mkdocs_config["copyright"] = f"Last updated: {datetime.now().strftime('%B %d, %Y')}"

    with open(mkdocs_path, "w", encoding="utf-8") as f:
        yaml.dump(mkdocs_config, f, default_flow_style=False,
                  allow_unicode=True, sort_keys=False)


def main():
    print("Syncing notes to docs/...")
    sync_notes_to_docs()
    sync_weekly_reviews()
    sync_weekly_quizzes()

    print("Building navigation...")
    nav = build_nav()

    print("Updating mkdocs.yml...")
    update_mkdocs_yml(nav)

    print("Done. Run 'mkdocs serve' to preview.")


if __name__ == "__main__":
    main()
